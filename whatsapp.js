// GET WHATSAPP CONNECTION STATUS
function getWhatsAppStatus(userId) {
    const id = String(userId);
    const status = connectionStates.get(id);
    const socket = activeSockets.get(id);

    if (!socket) {
        if (status === "stopped") return "stopped";
        if (status === "reconnecting") return "reconnecting";
        if (status === "connecting") return "connecting";
        return "disconnected";
    }

    if (status === "connected" && socket.user) {
        return "connected";
    }

    return status || "connecting";
}

// GET CONNECTED WHATSAPP NUMBER
function getConnectedWhatsAppNumber(userId) {
    const socket = activeSockets.get(String(userId));

    if (socket && socket.user) {
        return socket.user.id.split(":")[0].split("@")[0];
    }

    return null;
}
// GENERATE PAIRING CODE
async function generatePairingCode(userId, phoneNumber) {
    const { useMultiFileAuthState } = await loadBaileys();

    phoneNumber = String(phoneNumber).replace(/\D/g, "");

    if (!/^\d{10,15}$/.test(phoneNumber)) {
        throw new Error("Enter a valid phone number with country code.");
    }

    if (!userId) {
        throw new Error("Customer ID is required.");
    }

    const id = String(userId);
    const existingSocket = activeSockets.get(id);
    const existingStatus = connectionStates.get(id);

    if (existingSocket && existingStatus !== "disconnected") {
        throw new Error(
            "A WhatsApp connection is already active or in progress. Please use Reconnect Saved WhatsApp if needed."
        );
    }

    const sessionKey = getWhatsAppSessionKey(userId);
    const sessionDirectory = path.join(sessionsDirectory, sessionKey);

    fs.mkdirSync(sessionDirectory, { recursive: true });

    const { state } = await useMultiFileAuthState(sessionDirectory);

    console.log("PAIRING SESSION REGISTERED:", state.creds.registered);

    if (state.creds.registered) {
        throw new Error("This WhatsApp account is already registered.");
    }

    if (existingSocket) {
        existingSocket.end(undefined);
        activeSockets.delete(id);
    }

    let sock;

    try {
        sock = await createWhatsAppSocket(userId, sessionKey);

        await new Promise(resolve => setTimeout(resolve, 3000));

        const pairingCode = await sock.requestPairingCode(phoneNumber);

        console.log("Pairing code request completed.");

        return { pairingCode };

    } catch (error) {
        console.error("Pairing process failed:", error.message);

        if (sock && activeSockets.get(id) === sock) {
            activeSockets.delete(id);
            connectionStates.set(id, "disconnected");

            try {
                sock.end(undefined);
            } catch (closeError) {
                console.log("Pairing socket cleanup completed.");
            }
        }

        throw error;
    }
}

// GENERATE WHATSAPP QR CODE
async function startWhatsAppQR(userId) {
    if (!userId) {
        throw new Error("Customer ID is required.");
    }

    const { useMultiFileAuthState } = await loadBaileys();
    const sessionKey = getWhatsAppSessionKey(userId);
    const sessionDirectory = path.join(sessionsDirectory, sessionKey);

    fs.mkdirSync(sessionDirectory, { recursive: true });

    const { state } = await useMultiFileAuthState(sessionDirectory);

    if (state.creds.registered) {
        throw new Error("This WhatsApp account is already registered. Use Reconnect Saved WhatsApp.");
    }

    const id = String(userId);
    const existingSocket = activeSockets.get(id);

    if (existingSocket) {
        existingSocket.end(undefined);
        activeSockets.delete(id);
    }

    let resolveQR;
    let qrTimer;

    const qrPromise = new Promise((resolve, reject) => {
        resolveQR = resolve;
        qrTimer = setTimeout(() => {
            reject(new Error("QR code was not received within 30 seconds. Please try again."));
        }, 30000);
    });

    const onQR = (qr) => {
        if (qr) {
            clearTimeout(qrTimer);
            resolveQR(qr);
        }
    };

    let sock;

    try {
        sock = await createWhatsAppSocket(userId, sessionKey, onQR);
        const qr = await qrPromise;
        return { qr };
    } catch (error) {
        clearTimeout(qrTimer);

        if (sock && activeSockets.get(id) === sock) {
            activeSockets.delete(id);
            try {
                sock.end(undefined);
            } catch (closeError) {
                console.log("QR socket cleanup completed.");
            }
        }

        throw error;
    }
}
