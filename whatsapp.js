function getOrAssignPrimaryGroupBot(groupJid, currentUserId) {
    if (!groupJid?.endsWith("@g.us")) return Number(currentUserId);

    const id = Number(currentUserId);
    if (!Number.isSafeInteger(id) || id <= 0) return null;

    db.prepare(`
        INSERT OR IGNORE INTO xmd_group_primary_bots
        (group_jid, primary_user_id)
        VALUES (?, ?)
    `).run(groupJid, id);

    const row = db.prepare(`
        SELECT primary_user_id
        FROM xmd_group_primary_bots
        WHERE group_jid = ?
    `).get(groupJid);

    return row ? Number(row.primary_user_id) : null;
}

