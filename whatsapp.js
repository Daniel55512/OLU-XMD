// START BOT USING THE CUSTOMER'S SAVED WHATSAPP SESSION
async function startWhatsApp(userId) {
    const currentStatus = getWhatsAppStatus(userId);

    if (currentStatus === "connected") {
        return {
            success: true,
            message: "WhatsApp bot is already connected."
        };
    }

    if (currentStatus === "connecting" || currentStatus === "reconnecting") {
        throw new Error("WhatsApp connection is already in progress.");
    }

    return await reconnectWhatsApp(userId);
}

// STOP BOT WITHOUT UNLINKING OR DELETING SAVED CREDENTIALS
async function stopWhatsApp(userId) {
    const id = String(userId);

    clearWhatsAppReconnect(id);
    reconnectAttempts.delete(id);

    // Validate the customer ID and session-key mapping.
    getWhatsAppSessionKey(userId);

    // Invalidate pending socket creation and automatic restart callbacks.
    socketGenerations.set(
        id,
        (socketGenerations.get(id) || 0) + 1
    );

    const socket = activeSockets.get(id);

    // Remove the socket before closing it so its close event is ignored.
    activeSockets.delete(id);
    connectionStates.set(id, "stopped");

    if (socket) {
        try {
            socket.end(undefined);
        } catch (error) {
            console.error("WhatsApp stop socket error:", error.message);
        }
    }

    return {
        success: true,
        message: "Bot stopped. Your WhatsApp remains linked."
    };
}
