// These errors require user/session intervention rather than automatic retries.
const TERMINAL_DISCONNECT_CODES = new Set([401, 403, 411, 440, 500]);

function clearWhatsAppReconnect(userId) {
    const id = String(userId);
    const timer = reconnectTimers.get(id);

    if (timer) clearTimeout(timer);

    reconnectTimers.delete(id);
}

function scheduleWhatsAppReconnect(userId, sessionKey, expectedGeneration, statusCode) {
    const id = String(userId);

    if (
        connectionStates.get(id) === "stopped" ||
        socketGenerations.get(id) !== expectedGeneration
    ) return;

    const numericStatus = Number(statusCode);

    if (TERMINAL_DISCONNECT_CODES.has(numericStatus)) {
        connectionStates.set(id, "disconnected");

        console.error("WHATSAPP AUTO-RECONNECT NOT ATTEMPTED:", {
            userId,
            statusCode: numericStatus,
            reason: "Session or connection requires manual intervention."
        });

        return;
    }

    if (reconnectTimers.has(id)) return;

    const attempt = (reconnectAttempts.get(id) || 0) + 1;
    reconnectAttempts.set(id, attempt);

    const baseDelay = numericStatus === 515 ? 1500 : 2000;
    const delayMs = Math.min(
        baseDelay * Math.pow(2, Math.min(attempt - 1, 5)),
        30000
    );

    connectionStates.set(id, "reconnecting");

    console.warn("WHATSAPP AUTO-RECONNECT SCHEDULED:", {
        userId,
        statusCode: Number.isFinite(numericStatus) ? numericStatus : null,
        attempt,
        delayMs
    });

    const timer = setTimeout(async () => {
        if (reconnectTimers.get(id) !== timer) return;

        reconnectTimers.delete(id);

        if (
            connectionStates.get(id) === "stopped" ||
            socketGenerations.get(id) !== expectedGeneration
        ) {
            console.log("WHATSAPP AUTO-RECONNECT CANCELLED:", userId);
            return;
        }

        console.log("WHATSAPP AUTO-RECONNECT ATTEMPT:", {
            userId,
            attempt
        });

        try {
            await createWhatsAppSocket(userId, sessionKey);
        } catch (error) {
            console.error("WHATSAPP AUTO-RECONNECT START FAILED:", {
                userId,
                error
            });

            if (connectionStates.get(id) === "stopped") return;

            const currentGeneration = socketGenerations.get(id);

            connectionStates.set(id, "reconnecting");

            scheduleWhatsAppReconnect(
                userId,
                sessionKey,
                currentGeneration,
                error?.output?.statusCode ?? null
            );
        }
    }, delayMs);

    reconnectTimers.set(id, timer);
}
